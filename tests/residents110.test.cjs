'use strict';
const assert=require('node:assert/strict');
const {derive,transact,fixture,identity,JOBS,validate}=require('../residents110.js');
const district=require('../district110.js');
const a=fixture(),before=JSON.stringify(a),m=derive(a.district);
assert.equal(m.capacity,4);assert.equal(m.population,2);assert.equal(m.employed,1);assert.equal(m.happiness,63);
assert.equal(m.slots.farmer,2);assert.equal(m.slots.lumberjack,2);assert.equal(m.slots.miner,0);
assert.equal(JOBS.length,7);assert.notEqual(identity(1).name,identity(13).name);
const b=transact(a.district,a.gold,{kind:'resident-recruit'});assert.equal(b.gold,450);assert.equal(derive(b.district).population,3);assert.equal(b.district.residents.people.at(-1).id,3);
assert.equal(JSON.stringify(a),before);
const c=transact(b.district,b.gold,{kind:'resident-assign',id:2,job:'farmer'});assert.equal(c.gold,450);assert.equal(derive(c.district).used.farmer,2);
assert.equal(transact(c.district,c.gold,{kind:'resident-assign',id:3,job:'farmer'}).reason,'slots');
const d=transact(c.district,c.gold,{kind:'resident-assign',id:1,job:'idle'});assert.equal(derive(d.district).used.farmer,1);
assert.equal(transact(d.district,d.gold,{kind:'resident-assign',id:3,job:'miner'}).reason,'slots');
assert.equal(transact(fixture('full').district,500,{kind:'resident-recruit'}).reason,'housing');
assert.equal(transact(fixture('empty').district,500,{kind:'resident-recruit'}).reason,'housing');
assert.equal(transact(fixture('poor').district,0,{kind:'resident-recruit'}).reason,'gold');
assert.equal(validate({nextId:2,people:[{id:1,job:'unknown'}]}),null);
assert.equal(derive({...a.district,buildings:[]}),null);
const move=district.transact(c.district,c.gold,{kind:'move',cell:3,to:9});assert.equal(move.ok,true);assert.deepEqual(derive(move.district).slots,derive(c.district).slots);assert.deepEqual(move.district.residents,c.district.residents);
console.log('PASS resident recruitment, job slots, happiness, housing, move compatibility and immutable transactions');
