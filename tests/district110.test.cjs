'use strict';
const assert=require('node:assert/strict');
const {SIZE,PLOTS,TYPES,fresh,validate,transact,fixture}=require('../district110.js');
assert.equal(SIZE,6);assert.equal(PLOTS.length,21);assert.equal(TYPES.length,8);
assert.deepEqual(validate(undefined),fresh());assert.equal(validate(null),null);assert.equal(validate({version:2,buildings:[]}),null);
const a=fixture(),before=JSON.stringify(a),cell=PLOTS[2],dest=PLOTS[3];
let b=transact(a.district,a.gold,{kind:'build',cell,type:'warehouse'});assert.equal(b.ok,true);assert.equal(b.gold,4760);assert.equal(b.district.buildings.length,3);
assert.equal(JSON.stringify(a),before);assert.equal(transact(b.district,b.gold,{kind:'build',cell,type:'house'}).reason,'occupied');
let c=transact(b.district,b.gold,{kind:'upgrade',cell});assert.equal(c.gold,4280);assert.equal(c.district.buildings.find(x=>x.cell===cell).level,2);
let d=transact(c.district,c.gold,{kind:'move',cell,to:dest});assert.equal(d.gold,c.gold);assert.equal(d.district.buildings.find(x=>x.cell===dest).level,2);assert.ok(!d.district.buildings.some(x=>x.cell===cell));
assert.equal(transact(d.district,d.gold,{kind:'move',cell:dest,to:PLOTS[0]}).reason,'occupied');
assert.equal(transact(d.district,d.gold,{kind:'move',cell:dest,to:2}).reason,'plot');
assert.equal(transact(fixture('poor').district,0,{kind:'build',cell,type:'house'}).reason,'gold');
assert.equal(transact(fixture('max').district,100000,{kind:'upgrade',cell}).reason,'max');
assert.equal(validate({version:1,buildings:[{cell,type:'house',level:1},{cell,type:'house',level:1}]}),null);
assert.equal(transact({version:2,buildings:[]},5000,{kind:'build',cell,type:'house'}).reason,'invalid');
assert.equal(transact(undefined,100,{kind:'build',cell,type:'house'}).reason,'gold');
assert.equal(transact(undefined,-1,{kind:'build',cell,type:'house'}).reason,'invalid');
console.log('PASS district plots, eight types, exact costs, move, max, poor, occupied and invalid saves');
