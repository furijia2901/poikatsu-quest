'use strict';
const assert=require('node:assert/strict');
const P=require('../production110.js'),R=require('../residents110.js'),D=require('../district110.js');
const {HOUR,CAP_MS,fixture,rates,settle,transact}=P;
const a=fixture(),before=JSON.stringify(a),r=rates(a.district);
assert.deepEqual(r.rates,{food:7326,wood:4440,stone:3330});assert.equal(r.capacity,225);assert.equal(r.artisans,1);
assert.ok(D.validate(a.district));assert.equal(JSON.stringify(a),before);
const b=settle(a.district,a.now);assert.deepEqual(b.gained,{food:7,wood:4,stone:3});assert.equal(b.elapsed,HOUR);assert.equal(JSON.stringify(a),before);
assert.deepEqual(settle(b.district,a.now).gained,{food:0,wood:0,stone:0});
const next=settle(b.district,a.now+HOUR),direct=settle(a.district,a.now+HOUR);
assert.deepEqual(next.district.production,direct.district.production);
const craft=transact(b.district,500,{kind:'production-craft',count:1},a.now);
assert.deepEqual(craft.district.production.stock,{food:7,wood:2,stone:2,goods:1});assert.equal(craft.gold,500);
assert.equal(transact(b.district,500,{kind:'production-craft',count:2},a.now).reason,'workers');
const offline=fixture('offline'),off=settle(offline.district,offline.now);assert.equal(off.elapsed,CAP_MS);assert.equal(off.gained.food,87);assert.equal(off.district.production.lastAt,offline.now);
const full=fixture('full');assert.deepEqual(settle(full.district,full.now).gained,{food:0,wood:0,stone:0});
const idle=fixture('idle');assert.deepEqual(settle(idle.district,idle.now).gained,{food:0,wood:0,stone:0});assert.equal(transact(idle.district,500,{kind:'production-craft',count:1},idle.now).reason,'workers');
const rollback=settle(b.district,a.now-HOUR);assert.equal(rollback.elapsed,0);assert.deepEqual(rollback.district.production,b.district.production);
const old=R.fixture().district,initial=settle(old,a.now);assert.deepEqual(initial.gained,{food:0,wood:0,stone:0});
const changed=R.transact(b.district,500,{kind:'resident-assign',id:1,job:'idle'});assert.equal(settle(changed.district,a.now+HOUR).gained.food,0);
assert.equal(settle({...a.district,production:{version:2}},a.now),null);
console.log('PASS production rates, skill bonus, exact fractional accrual, twelve-hour cap, storage, crafting, time rollback and previous-rate settlement');
